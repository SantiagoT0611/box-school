-- Esquema tal como lo dejo Hibernate ddl-auto=update en la base de desarrollo real, ANTES de Flyway.
-- Incluye los "restos" que V1 no contempla: payments.amount NOT NULL, FK vieja a la tabla "price",
-- students.email sin UNIQUE, columnas nullable y CHECK de enums con valores antiguos (EXPIRED).

create table students (
    id bigint generated by default as identity primary key,
    email varchar(255),
    expiration_date date,
    first_name varchar(255),
    last_name varchar(255),
    phone varchar(255),
    registration_date date,
    status varchar(255) check (status in ('ACTIVE', 'INACTIVE', 'EXPIRED'))
);

create table users (
    id bigint generated by default as identity primary key,
    enabled boolean not null,
    password varchar(255) not null,
    role varchar(255) not null check (role in ('ROLE_ADMIN', 'ROLE_USER')),
    username varchar(255) not null unique,
    student_id bigint unique,
    constraint fk_users_student_legacy foreign key (student_id) references students
);

create table price (
    id bigint generated by default as identity primary key,
    active boolean,
    amount numeric(38, 2),
    created_at timestamp(6),
    duration_days integer,
    type varchar(255)
);

create table prices (
    id bigint generated by default as identity primary key,
    active boolean not null,
    amount numeric(19, 2) not null,
    created_at timestamp(6) not null,
    duration_days integer not null,
    type varchar(255) not null check (type in ('BIWEEKLY', 'MONTHLY'))
);

create table payments (
    id bigint generated by default as identity primary key,
    amount numeric(38, 2) not null,
    amount_paid numeric(19, 2) not null,
    payment_date date not null,
    period_end date not null,
    period_start date not null,
    price_id bigint not null,
    student_id bigint not null,
    constraint fk_payments_price_legacy foreign key (price_id) references price,
    constraint fk_payments_prices foreign key (price_id) references prices,
    constraint fk_payments_student_legacy foreign key (student_id) references students
);

create table invoices (
    id bigint generated by default as identity primary key,
    invoice_number integer not null unique,
    issue_date date not null,
    period_end date not null,
    period_start date not null,
    total numeric(19, 2) not null,
    student_id bigint not null,
    constraint fk_invoices_student_legacy foreign key (student_id) references students
);

