package com.storres.box_school;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import org.flywaydb.core.api.configuration.Configuration;
import org.flywaydb.core.api.migration.Context;
import org.junit.jupiter.api.Test;

import db.migration.V5__repair_legacy_schema;

/**
 * Reproduce el esquema que dejo Hibernate ddl-auto=update en la base de desarrollo real
 * (FK vieja a la tabla "price", sin UNIQUE en students.email, columna payments.amount) y comprueba
 * que la migracion V5 lo repara sin tocar datos y que es idempotente.
 */
class LegacySchemaRepairTest {

    private static final String URL = "jdbc:h2:mem:legacy;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1";

    private static Context contextFor(Connection connection) {
        return new Context() {
            @Override
            public Configuration getConfiguration() {
                return null;
            }

            @Override
            public Connection getConnection() {
                return connection;
            }
        };
    }

    @Test
    void repairsLegacyForeignKeyAndMissingUniqueAndIsIdempotent() throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement st = c.createStatement()) {
            st.execute("create table students (id bigint generated by default as identity primary key, email varchar(255))");
            st.execute("create table users (id bigint generated by default as identity primary key, username varchar(255) not null, student_id bigint)");
            st.execute("create table invoices (id bigint generated by default as identity primary key, invoice_number integer, student_id bigint)");
            st.execute("create table price (id bigint generated by default as identity primary key)"); // tabla huerfana
            st.execute("create table prices (id bigint generated by default as identity primary key)");
            st.execute("create table payments (id bigint generated by default as identity primary key, "
                    + "student_id bigint, price_id bigint, "
                    + "constraint fk_legacy_price foreign key (price_id) references price (id), "
                    + "constraint fk_legacy_student foreign key (student_id) references students (id))");
            st.execute("insert into students (email) values ('ana@test.com')");
            st.execute("insert into prices (id) values (1)");

            // Antes: insertar un pago con un precio de "prices" falla por la FK a "price"
            assertThatThrownBy(() -> st.execute("insert into payments (student_id, price_id) values (1, 1)"))
                    .isInstanceOf(SQLException.class);

            new V5__repair_legacy_schema().migrate(contextFor(c));

            st.execute("insert into payments (student_id, price_id) values (1, 1)"); // ahora funciona
            assertThat(foreignKeyTargets(c, "payments")).containsExactlyInAnyOrder("prices", "students");
            assertThatThrownBy(() -> st.execute("insert into students (email) values ('ana@test.com')"))
                    .as("students.email debe quedar UNIQUE").isInstanceOf(SQLException.class);
            assertThat(count(st, "select count(*) from students")).isEqualTo(1); // no toco datos

            new V5__repair_legacy_schema().migrate(contextFor(c)); // idempotente: no falla ni duplica nada
            assertThat(foreignKeyTargets(c, "payments")).containsExactlyInAnyOrder("prices", "students");
        }
    }

    @Test
    void failsLoudlyInsteadOfTouchingDataWhenDuplicatesBlockAUniqueConstraint() throws Exception {
        try (Connection c = DriverManager.getConnection("jdbc:h2:mem:legacy2;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
                Statement st = c.createStatement()) {
            st.execute("create table students (id bigint generated by default as identity primary key, email varchar(255))");
            st.execute("insert into students (email) values ('dup@test.com'), ('dup@test.com')");

            assertThatThrownBy(() -> new V5__repair_legacy_schema().migrate(contextFor(c)))
                    .isInstanceOf(SQLException.class);
            assertThat(count(st, "select count(*) from students")).isEqualTo(2); // datos intactos
        }
    }

    private static List<String> foreignKeyTargets(Connection c, String table) throws SQLException {
        List<String> targets = new ArrayList<>();
        try (ResultSet rs = c.getMetaData().getImportedKeys(null, c.getSchema(), table)) {
            while (rs.next()) {
                targets.add(rs.getString("PKTABLE_NAME").toLowerCase());
            }
        }
        return targets;
    }

    private static int count(Statement st, String sql) throws SQLException {
        try (ResultSet rs = st.executeQuery(sql)) {
            rs.next();
            return rs.getInt(1);
        }
    }
}
