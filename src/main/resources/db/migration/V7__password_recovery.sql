-- V7: recuperacion y cambio de contrasena (ver docs/DECISIONS.md D-024).

-- Version de la sesion: se incrementa al cambiar o restablecer la clave. El JWT lleva la version con la que se
-- emitio (claim "ver"); si no coincide con la actual, el token deja de valer (cierra las sesiones abiertas).
alter table users add column token_version integer not null default 0;

-- Token de recuperacion: un solo uso, solo se guarda su SHA-256 y a lo sumo hay UNO por usuario
-- (pedir uno nuevo reemplaza al anterior), asi que la tabla no crece mas alla del numero de usuarios.
create table password_reset_tokens (
    id         bigint generated by default as identity primary key,
    user_id    bigint       not null,
    token_hash varchar(64)  not null,
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    used_at    timestamp(6),
    constraint uk_password_reset_token_hash unique (token_hash),
    constraint uk_password_reset_user unique (user_id),
    constraint fk_password_reset_user foreign key (user_id) references users (id) on delete cascade
);
